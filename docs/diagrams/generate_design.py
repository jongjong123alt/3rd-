"""Generate editable, uncompressed diagrams.net/draw.io XML using only stdlib.
Run from any directory: python docs/diagrams/generate_design.py
No application data or credentials are read.
"""
from pathlib import Path
import html
import xml.etree.ElementTree as ET

OUT = Path(__file__).resolve().parent
FONT = 'Noto Sans CJK KR'
COLORS = {'normal':('#F8FAFC','#CBD5E1'), 'action':('#E9F2EB','#7BA58A'),
          'decision':('#FFF4DA','#CFAE67'), 'error':('#FDEDE9','#CE958A'),
          'external':('#EDEFFB','#9CA7CF'), 'data':('#E7F1F6','#85AABA')}
mxfile = ET.Element('mxfile', {'host':'app.diagrams.net','agent':'Project design documentation',
                             'version':'24.7.17','type':'device','compressed':'false'})


class Page:
    def __init__(self, ident, title, subtitle, height=1200):
        self.ident=ident;self.count=0
        diagram=ET.SubElement(mxfile,'diagram',{'id':ident,'name':title})
        model=ET.SubElement(diagram,'mxGraphModel',{'dx':'1600','dy':str(height),'grid':'1','gridSize':'10','guides':'1','tooltips':'1','connect':'1','arrows':'1','fold':'1','page':'1','pageScale':'1','pageWidth':'1600','pageHeight':str(height),'math':'0','shadow':'0'})
        self.root=ET.SubElement(model,'root')
        ET.SubElement(self.root,'mxCell',{'id':'0'})
        ET.SubElement(self.root,'mxCell',{'id':'1','parent':'0'})
        self.text('heading',title,40,26,1510,45,26,True)
        self.text('subtitle',subtitle,40,78,1510,42,13)
        self.text('footer','과제 노트 · 구현 기준 537e49f · 2026-11-24 · 실선: 실제 처리 / 점선: 논리 관계 또는 보조 경로',40,height-47,1520,28,11)
    def _cell(self,ident,value,style,x,y,w,h):
        c=ET.SubElement(self.root,'mxCell',{'id':ident,'value':value,'style':style,'vertex':'1','parent':'1'})
        ET.SubElement(c,'mxGeometry',{'x':str(x),'y':str(y),'width':str(w),'height':str(h),'as':'geometry'})
        return ident
    def text(self,i,value,x,y,w,h,size=13,bold=False):
        return self._cell(i,html.escape(value),f'shape=rectangle;fillColor=none;strokeColor=none;html=1;whiteSpace=wrap;align=left;verticalAlign=middle;fontColor=#334155;fontFamily={FONT};fontSize={size};fontStyle={1 if bold else 0};spacing=0;',x,y,w,h)
    def node(self,i,title,body,x,y,w=300,h=85,kind='normal',shape='round',left=False):
        fill,stroke=COLORS[kind]
        shape_style='shape=ellipse;' if shape=='ellipse' else 'shape=rhombus;' if shape=='decision' else 'rounded=1;arcSize=12;'
        label=f'<b>{html.escape(title)}</b>'
        if body:label+='<br><span style="font-size:12px">'+html.escape(body).replace('\n','<br>')+'</span>'
        return self._cell(i,label,shape_style+f'html=1;whiteSpace=wrap;fillColor={fill};strokeColor={stroke};strokeWidth=1.5;fontColor=#24352E;fontSize=15;fontFamily={FONT};align={"left" if left else "center"};verticalAlign=middle;spacing=14;',x,y,w,h)
    def edge(self,source,target,label='',points=(),dashed=False,exit=None,entry=None):
        self.count+=1
        style='edgeStyle=orthogonalEdgeStyle;rounded=0;orthogonalLoop=1;jettySize=auto;html=1;endArrow=block;endFill=1;strokeColor=#64748B;strokeWidth=1.5;labelBackgroundColor=#FFFFFF;fontColor=#334155;fontSize=12;fontFamily='+FONT+';'
        if dashed:style+='dashed=1;'
        if exit:style+=f'exitX={exit[0]};exitY={exit[1]};exitDx=0;exitDy=0;'
        if entry:style+=f'entryX={entry[0]};entryY={entry[1]};entryDx=0;entryDy=0;'
        c=ET.SubElement(self.root,'mxCell',{'id':f'edge-{self.count}','value':html.escape(label),'style':style,'edge':'1','parent':'1','source':source,'target':target})
        g=ET.SubElement(c,'mxGeometry',{'relative':'1','as':'geometry'})
        if points:
            arr=ET.SubElement(g,'Array',{'as':'points'})
            for x,y in points:ET.SubElement(arr,'mxPoint',{'x':str(x),'y':str(y)})


